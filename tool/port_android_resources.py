#!/usr/bin/env python3
"""Ports Android design resources into the Flutter app (run on a dev machine).

  tool/port_android_resources.py /path/to/racketmates-android [drawable ...]

* lib/app/theme/native_palette.g.dart: every colour of `colors.xml` /
  `config_colors.xml`, day and night, resolved (names in camelCase).
* assets/icons/<name>.svg for the vector drawables named on the command line.
* assets/fonts/ (Inter) and assets/video/ (landing videos) copied as they are.

Nothing here is secret; re-run it when the native design changes.
"""
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

android = Path(sys.argv[1])
res = android / "app/src/main/res"
root = Path(__file__).resolve().parent.parent
A = "{http://schemas.android.com/apk/res/android}"
AAPT = "{http://schemas.android.com/aapt}"


def load(files):
    d = {}
    for f in files:
        p = res / f
        if not p.exists():
            continue
        for m in re.finditer(r'<color name="([^"]+)"[^>]*>([^<]+)</color>', p.read_text()):
            d[m.group(1)] = m.group(2).strip()
    return d


light = load(["values/colors.xml", "values/config_colors.xml"])
night = dict(light)
night.update(load(["values-night/colors.xml", "values-night/config_colors.xml"]))


def resolve(d, name, depth=0):
    v = d.get(name)
    while v and v.startswith("@color/") and depth < 20:
        v = d.get(v[7:])
        depth += 1
    return v


def dart_color(v):
    v = v.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    if len(v) == 6:
        v = "FF" + v
    if len(v) != 8:
        return None
    return "Color(0x%s)" % v.upper()


def camel(n):
    parts = re.split(r"[_\W]+", n)
    s = parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return ("c" + s[:1].upper() + s[1:]) if s[:1].isdigit() else s


names = sorted(n for n in light if dart_color(resolve(light, n) or "") and dart_color(resolve(night, n) or ""))
fields, ctor, lrows, drows = [], [], [], []
for n in names:
    f = camel(n)
    if f in ("hashCode", "runtimeType", "toString"):
        f += "Color"
    fields.append(f"  final Color {f};")
    ctor.append(f"    required this.{f},")
    lrows.append(f"    {f}: {dart_color(resolve(light, n))},")
    drows.append(f"    {f}: {dart_color(resolve(night, n))},")
out = "// GENERATED by tool/port_android_resources.py from the native colors.xml /\n"
out += "// config_colors.xml (values and values-night). Do not edit by hand.\n"
out += "// ignore_for_file: public_member_api_docs\n\nimport 'package:flutter/widgets.dart';\n\n"
out += "class NativePalette {\n  const NativePalette({\n" + "\n".join(ctor) + "\n  });\n\n" + "\n".join(fields)
out += "\n\n  static const light = NativePalette(\n" + "\n".join(lrows) + "\n  );\n\n"
out += "  static const dark = NativePalette(\n" + "\n".join(drows) + "\n  );\n}\n"
(root / "lib/app/theme/native_palette.g.dart").write_text(out)
print(f"palette: {len(names)} colours")


def color_of(v):
    if not v:
        return None
    if v.startswith("@color/"):
        v = resolve(light, v[7:])
    if not v:
        return None
    v = v.lstrip("#")
    if len(v) == 8:
        return "#" + v[2:], int(v[:2], 16) / 255
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    return "#" + v, 1.0


def vector_to_svg(path):
    tree = ET.parse(path).getroot()
    vw, vh = tree.get(A + "viewportWidth"), tree.get(A + "viewportHeight")
    w = (tree.get(A + "width") or vw).replace("dp", "")
    h = (tree.get(A + "height") or vh).replace("dp", "")
    defs, body = [], []
    counter = [0]

    def gradient(el):
        g = el.find(f".//{AAPT}attr/gradient") if False else None
        attr = el.find(AAPT + "attr")
        if attr is None:
            return None
        g = attr.find("gradient")
        if g is None:
            return None
        counter[0] += 1
        gid = f"g{counter[0]}"
        stops = ""
        for item in g.findall("item"):
            c, a = color_of(item.get(A + "color")) or ("#000000", 1)
            stops += f'<stop offset="{item.get(A + "offset")}" stop-color="{c}" stop-opacity="{a}"/>'
        kind = g.get(A + "type")
        if kind == "radial":
            defs.append(
                f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{g.get(A + "centerX")}" '
                f'cy="{g.get(A + "centerY")}" r="{g.get(A + "gradientRadius")}">{stops}</radialGradient>'
            )
        else:
            defs.append(
                f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{g.get(A + "startX")}" '
                f'y1="{g.get(A + "startY")}" x2="{g.get(A + "endX")}" y2="{g.get(A + "endY")}">{stops}</linearGradient>'
            )
        return gid

    def walk(el):
        for child in el:
            if child.tag == "group":
                tf = []
                tx, ty = child.get(A + "translateX"), child.get(A + "translateY")
                if tx or ty:
                    tf.append(f"translate({tx or 0} {ty or 0})")
                rot = child.get(A + "rotation")
                if rot:
                    tf.append(f"rotate({rot} {child.get(A + 'pivotX') or 0} {child.get(A + 'pivotY') or 0})")
                sx, sy = child.get(A + "scaleX"), child.get(A + "scaleY")
                if sx or sy:
                    tf.append(f"scale({sx or 1} {sy or 1})")
                body.append(f'<g transform="{" ".join(tf)}">' if tf else "<g>")
                walk(child)
                body.append("</g>")
            elif child.tag == "path":
                d = child.get(A + "pathData")
                if not d:
                    continue
                attrs = [f'd="{d}"']
                gid = gradient(child)
                fill = child.get(A + "fillColor")
                if gid:
                    attrs.append(f'fill="url(#{gid})"')
                elif fill:
                    c, a = color_of(fill) or ("#000000", 1)
                    attrs.append(f'fill="{c}"')
                    fa = float(child.get(A + "fillAlpha") or 1) * a
                    if fa < 1:
                        attrs.append(f'fill-opacity="{fa}"')
                else:
                    attrs.append('fill="none"')
                if child.get(A + "fillType") == "evenOdd":
                    attrs.append('fill-rule="evenodd"')
                stroke = child.get(A + "strokeColor")
                if stroke:
                    c, a = color_of(stroke) or ("#000000", 1)
                    attrs.append(f'stroke="{c}" stroke-width="{child.get(A + "strokeWidth") or 1}"')
                    for k, svgk in (("strokeLineCap", "stroke-linecap"), ("strokeLineJoin", "stroke-linejoin")):
                        if child.get(A + k):
                            attrs.append(f'{svgk}="{child.get(A + k)}"')
                body.append("<path " + " ".join(attrs) + "/>")

    walk(tree)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {vw} {vh}">'
        + ("<defs>" + "".join(defs) + "</defs>" if defs else "")
        + "".join(body)
        + "</svg>\n"
    )


for name in sys.argv[2:]:
    src = res / "drawable" / f"{name}.xml"
    if not src.exists() or ET.parse(src).getroot().tag != "vector":
        print(f"skip {name} (not a vector drawable)")
        continue
    (root / "assets/icons" / f"{name}.svg").write_text(vector_to_svg(src))
    print(f"icon: {name}")

for f in (res / "font").glob("inter_*.ttf"):
    shutil.copy(f, root / "assets/fonts" / f.name)
for f in (res / "raw").glob("racketmates_*.mp4"):
    shutil.copy(f, root / "assets/video" / f.name)
print("fonts and videos copied")
